def haversine_distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculates great-circle distance between two GPS points in kilometers."""
    r = 6371.0
    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    delta_phi = math.radians(lat2 - lat1)
    delta_lambda = math.radians(lon2 - lon1)

    a = (math.sin(delta_phi / 2.0) ** 2 +
         math.cos(phi1) * math.cos(phi2) *
         math.sin(delta_lambda / 2.0) ** 2)
    c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))
    return round(r * c, 1)


def find_spots_near_gps(lat: float, lon: float, max_spots: int = 10) -> list:
    """
    Returns spots from the catalog sorted by distance from the rider's coordinates.
    Guarantees that spots around you are shown first.
    """
    ranked = []
    for spot in GLOBAL_KITE_SPOTS:
        dist = haversine_distance_km(lat, lon, spot["lat"], spot["lon"])
        s_copy = dict(spot)
        s_copy["distance_km"] = dist
        ranked.append(s_copy)

    ranked.sort(key=lambda s: s["distance_km"])
    return ranked[:max_spots]


def search_spots_catalog(query: str, max_results: int = 15) -> list:
    """Searches predefined kite spots across name, country, region, and aliases."""
    if not query:
        return GLOBAL_KITE_SPOTS[:max_results]
    
    q = query.strip().lower()
    matches = []
    for spot in GLOBAL_KITE_SPOTS:
        name_clean = spot["name"].lower()
        country_clean = spot["country"].lower()
        region_clean = spot["region"].lower()
        aliases = [a.lower() for a in spot.get("aliases", [])]

        score = 0
        if q == spot["id"]:
            score = 100
        elif q in name_clean:
            score = 80
        elif any(q in a for a in aliases):
            score = 70
        elif q in country_clean or q in region_clean:
            score = 50

        if score > 0:
            s_copy = dict(spot)
            s_copy["match_score"] = score
            matches.append(s_copy)

    matches.sort(key=lambda s: -s["match_score"])
    return matches[:max_results]

def get_spot_conditions(spot: dict) -> dict:
    """Returns curated spot water conditions, depth, bottom type, and badges for riders."""
    name_l = (spot.get("name") or "").lower()
    s_type = spot.get("spot_type") or "ocean"
    
    # 1. Water Type
    if s_type == "lagoon" or any(k in name_l for k in ["lagoon", "lagoa", "mar menor", "stagnone", "mangroovy", "shark bay", "cauipe", "guajiru", "hatteras", "soma bay"]):
        water_type = "Lagoon / Flat Water"
        water_icon = "🏝️"
    elif s_type == "lake" or any(k in name_l for k in ["lake", "garda", "como", "silvaplana", "uri", "reschen"]):
        water_type = "Freshwater Lake"
        water_icon = "🏔️"
    elif any(k in name_l for k in ["pozo", "one eye", "manawa", "ponta preta", "hookipa", "guincho", "pacasmayo", "cotillo"]):
        water_type = "Ocean Waves"
        water_icon = "🏄"
    else:
        water_type = "Ocean Chop & Swell"
        water_icon = "🌊"

    # 2. Bottom Type
    if any(k in name_l for k in ["pozo", "one eye", "reef", "le morne", "dakhla speed", "fuerteventura", "lanzarote", "famara"]):
        bottom_type = "Reef / Booties Advised"
        bottom_icon = "🪨"
    elif s_type == "lake" or any(k in name_l for k in ["garda", "como", "torbole", "colico"]):
        bottom_type = "Pebble / Grass Launch"
        bottom_icon = "⛰️"
    else:
        bottom_type = "Sand Bottom"
        bottom_icon = "🏖️"

    # 3. Depth
    if s_type == "lagoon" or any(k in name_l for k in ["mar menor", "cauipe", "taiba lagoon", "el gouna", "lo stagnone", "shark bay", "guajiru", "hatteras"]):
        depth = "Waist-Deep"
        depth_icon = "🚶"
    else:
        depth = "Deep Water"
        depth_icon = "🏊"

    is_enclosed = s_type in ["lagoon", "lake"] or any(k in name_l for k in ["lagoon", "lagoa", "mar menor", "stagnone", "reschensee", "see", "lac", "dam", "estuary"])

    return {
        "water_type": water_type,
        "water_icon": water_icon,
        "bottom_type": bottom_type,
        "bottom_icon": bottom_icon,
        "depth": depth,
        "depth_icon": depth_icon,
        "is_enclosed": is_enclosed,
        "badges": [
            f"{water_icon} {water_type}",
            f"{depth_icon} {depth}",
            f"{bottom_icon} {bottom_type}"
        ]
    }

